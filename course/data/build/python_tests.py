MODULES = {1: M1, 2: M2, 3: M3, 4: M4, 5: M5, 6: M6}


def run(code):
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        exec(compile(code, "<test>", "exec"), {})
    return buf.getvalue().rstrip("\n")


def opt_text(o):
    return o if isinstance(o, str) else o[0]


def build():
    data = {}
    for number, qs in MODULES.items():
        assert len(qs) == 20, f"модуль {number}: {len(qs)} вопросов, нужно 20"
        seen = set()
        out = []
        for i, q in enumerate(qs, 1):
            where = f"модуль {number}, вопрос {i}"
            opts = [list(o) if not isinstance(o, str) else o for o in q["options"]]
            assert len(opts) == 4, where
            assert len({opt_text(o) for o in opts}) == 4, f"{where}: одинаковые варианты"
            assert 0 <= q["answer"] < 4, where
            assert q["q"][0] and q["q"][1], f"{where}: нет текста"
            key = (q["q"][0], q["code"])
            assert key not in seen, f"{where}: повтор"
            seen.add(key)
            if q["run"]:
                got = run(q["code"])
                want = q["out"] if q["out"] is not None else opt_text(opts[q["answer"]])
                assert got == want, f"{where}: программа выводит {got!r}, а верный ответ {want!r}"
                # ни один неверный вариант не должен совпадать с выводом
                for j, o in enumerate(opts):
                    if j != q["answer"] and q["out"] is None:
                        assert opt_text(o) != got, f"{where}: вариант {j} тоже верный"
            elif q["code"]:
                try:
                    run(q["code"])
                except Exception:
                    pass
                else:
                    raise AssertionError(f"{where}: ожидалась ошибка, но программа работает")
            out.append({"q": q["q"], "code": q["code"], "options": opts, "answer": q["answer"]})
        data[str(number)] = out
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(json.dumps(data, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"Python: {sum(len(v) for v in data.values())} вопросов в {len(data)} модулях → {OUT.name}")


if __name__ == "__main__":
    build()
