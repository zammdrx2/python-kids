def show(sel):
    """h1 → <h1>, остальные селекторы как есть."""
    import re
    return f"<{sel}>" if re.fullmatch(r"[a-z][a-z0-9]*", sel) else sel


def _m(ru, kk, msg):
    return msg or [ru, kk]


def E(sel, msg=None):
    return {"check": "exists", "sel": sel, "msg": _m(f"На странице есть {show(sel)}", f"Бетте {show(sel)} бар", msg)}


def N(sel, mn, mx=None, msg=None):
    c = {"check": "count", "sel": sel, "min": mn,
         "msg": _m(f"Элементов {show(sel)}: не меньше {mn}", f"{show(sel)} элементтері: кемінде {mn}", msg)}
    if mx is not None:
        c["max"] = mx
    return c


def TX(sel, text, msg=None):
    return {"check": "text", "sel": sel, "text": text,
            "msg": _m(f"В {show(sel)} есть текст «{text}»", f"{show(sel)} ішінде «{text}» мәтіні бар", msg)}


def A(sel, attr, value=None, msg=None):
    c = {"check": "attr", "sel": sel, "attr": attr}
    if value is None:
        c["msg"] = _m(f"У {show(sel)} есть атрибут {attr}", f"{show(sel)} элементінде {attr} атрибуты бар", msg)
    else:
        c["value"] = value
        c["msg"] = _m(f"У {show(sel)} атрибут {attr} содержит «{value}»", f"{show(sel)} элементінің {attr} атрибутында «{value}» бар", msg)
    return c


def CS(sel, prop, value, msg=None):
    return {"check": "css", "sel": sel, "prop": prop, "value": value,
            "msg": _m(f"У {show(sel)} стиль {prop}: {value}", f"{show(sel)} стилі {prop}: {value}", msg)}


def CN(sel, prop, value, msg):
    return {"check": "cssnot", "sel": sel, "prop": prop, "value": value, "msg": msg}


def W(title, text, hint, starter, solution, checks):
    return {"kind": "web", "title": title, "text": text, "hint": hint,
            "starter": starter, "solution": solution, "tests": checks}


